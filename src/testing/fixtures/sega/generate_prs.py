#!/usr/bin/env python3
"""Generate synthetic PRS decode goldens using prs-rs 2.0.3 (CC0 1.0)."""

import argparse
import hashlib
from pathlib import Path
import subprocess
import tempfile


# This standalone helper has no dependency on Ludared or its codec.
RUST = r'''
use std::{env, fs, path::Path};
use prs_rs::{comp::prs_compress_unsafe, decomp::prs_decompress_unsafe,
             util::prs_calculate_max_compressed_size};

fn main() {
    let args: Vec<_> = env::args().skip(1).collect();
    let output = Path::new(&args[0]);
    for input in &args[1..] {
        let source = fs::read(input).unwrap();
        let mut encoded = vec![0; prs_calculate_max_compressed_size(source.len())];
        // SAFETY: valid source slice and destination sized by prs-rs's bound.
        let length = unsafe {
            prs_compress_unsafe(source.as_ptr(), source.len(), encoded.as_mut_slice())
        };
        encoded.truncate(length);
        let mut decoded = vec![0; source.len()];
        // SAFETY: valid stream from prs-rs and known original decoded size.
        let written = unsafe {
            prs_decompress_unsafe(encoded.as_slice(), decoded.as_mut_slice())
        };
        assert_eq!(written, source.len());
        assert_eq!(decoded, source);
        let name = Path::new(input).file_stem().unwrap();
        fs::write(output.join(name).with_extension("prs"), encoded).unwrap();
    }
}
'''


def sources():
  mixed = bytearray(b"ab1ab2ab3ab1ab2ab3ab9ab1ab2ab3")
  for i, length in enumerate([1, 2, 3, 4, 5, 6, 9, 10, 255, 256, 257, 511]):
    mixed.extend(bytes([0xff if i % 2 == 0 else 0]) * length)
    mixed.extend(b"shared suffix beyond the repeated-byte run" * 3)
    mixed.append(i)
  mixed.extend(b"ab" * 300 + b"X" + b"ab" * 300)

  # Explicit xorshift32 arithmetic avoids platform/RNG-library dependencies.
  state = 0x12345678
  distant = bytearray()
  for _ in range(8191):
    state ^= (state << 13) & 0xffffffff
    state ^= state >> 17
    state ^= (state << 5) & 0xffffffff
    distant.append(state & 0xff)
  distant.extend(distant[:256])
  return {
    "empty": b"",
    "literals": bytes(range(256)),
    "mixed_copies": bytes(mixed),
    "distant_copy": bytes(distant),
  }


def main():
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument("--check", action="store_true", help="verify existing fixtures without replacing them")
  args = parser.parse_args()
  fixtures = Path(__file__).resolve().parent
  inputs = sources()
  # Expected decode hashes come directly from source content, before compression.
  hashes = {name: hashlib.sha256(data).hexdigest() for name, data in inputs.items()}
  with tempfile.TemporaryDirectory(prefix="ludared-prs-goldens-") as temporary:
    root = Path(temporary)
    (root / "src").mkdir()
    (root / "encoded").mkdir()
    (root / "src/main.rs").write_text(RUST)
    (root / "Cargo.toml").write_text(
      '[package]\nname = "prs-fixture-generator"\nversion = "0.0.0"\nedition = "2024"\n'
      '[dependencies]\nprs-rs = "=2.0.3"\n'
    )
    for name, data in inputs.items():
      (root / f"{name}.bin").write_bytes(data)
    subprocess.run([
      "cargo", "run", "--quiet", "--release", "--offline", "--manifest-path", str(root / "Cargo.toml"),
      "--", str(root / "encoded"), *(str(root / f"{name}.bin") for name in inputs),
    ], check=True)
    print("| Fixture | PRS bytes | PRS SHA-256 | Decoded bytes | Decoded SHA-256 |")
    print("|---|---:|---|---:|---|")
    for name, data in inputs.items():
      encoded = (root / "encoded" / f"{name}.prs").read_bytes()
      destination = fixtures / f"{name}.prs"
      if args.check:
        assert destination.read_bytes() == encoded, f"{name}: regenerated bytes differ"
      else:
        destination.write_bytes(encoded)
      print(f"| `{name}.prs` | {len(encoded)} | `{hashlib.sha256(encoded).hexdigest()}` | {len(data)} | `{hashes[name]}` |")


if __name__ == "__main__":
  main()
